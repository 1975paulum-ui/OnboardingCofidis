const LANGS = ['es', 'fr', 'en'];
const LOCALES = { es: 'es-ES', fr: 'fr-FR', en: 'en-GB' };

let LANG = (() => {
  try { const s = localStorage.getItem('lang'); if (LANGS.includes(s)) return s; } catch { /* sin acceso */ }
  return 'fr';
})();

/** Traduce una clave; admite marcadores {nombre}. Si falta, usa el francés y por último la propia clave. */
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.fr[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}

const localeTag = () => LOCALES[LANG] || 'fr-FR';

/** Traduce el marcado estático: data-i18n (texto), data-i18n-html (HTML) y data-i18n-attr="atributo:clave;…" */
function applyI18n() {
  document.documentElement.lang = LANG;
  document.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(';').forEach((pair) => {
      const [attr, key] = pair.split(':').map((x) => x.trim());
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
  document.querySelectorAll('[data-setlang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.setlang === LANG)));
}

function setLang(l) {
  if (!LANGS.includes(l) || l === LANG) return;
  LANG = l;
  try { localStorage.setItem('lang', l); } catch { /* sin acceso */ }
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange'));
}

document.addEventListener('click', (e) => {
  const b = e.target.closest('[data-setlang]');
  if (b) setLang(b.dataset.setlang);
});
